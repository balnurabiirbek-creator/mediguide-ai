extension AppLocalizationContext on BuildContext {
  String tr(String key, {Map<String, String> params = const {}}) {
    final localeCode = watch<AppPreferencesProvider>().localeCode;
    return AppLocalizations.translate(localeCode, key, params: params);
  }

  String dynamicText(String source) {
    final localeCode = watch<AppPreferencesProvider>().localeCode;
    return AppLocalizations.translateDynamic(localeCode, source);
  }

  String symptomLabel(String source) {
    final localeCode = watch<AppPreferencesProvider>().localeCode;
    return AppLocalizations.symptomLabel(localeCode, source);
  }

  String greeting() {
    final localeCode = watch<AppPreferencesProvider>().localeCode;
    return AppLocalizations.greetingForTime(localeCode, DateTime.now());
  }
}
