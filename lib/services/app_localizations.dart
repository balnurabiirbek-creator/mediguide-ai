  static String translate(
    String localeCode,
    String key, {
    Map<String, String> params = const {},
  }) {
    final language = _strings[localeCode] ?? _strings[fallbackLocale]!;
    var value = language[key] ?? _strings[fallbackLocale]![key] ?? key;

    for (final entry in params.entries) {
      value = value.replaceAll('{${entry.key}}', entry.value);
    }

    return value;
  }

  static String translateDynamic(String localeCode, String source) {
    if (localeCode == fallbackLocale) return source;
    return _dynamicStrings[localeCode]?[source] ?? source;
  }

  static String symptomLabel(String localeCode, String symptom) {
    if (localeCode == fallbackLocale) return symptom;
    return _symptomLabels[symptom]?[localeCode] ?? symptom;
  }

  static String canonicalSymptom(String input) {
    final normalized = input.trim().toLowerCase();
    if (normalized.isEmpty) return input.trim();

    for (final entry in _symptomLabels.entries) {
      if (entry.key.toLowerCase() == normalized) {
        return entry.key;
      }
      for (final localized in entry.value.values) {
        if (localized.toLowerCase() == normalized) {
          return entry.key;
        }
      }
    }

    return input.trim();
  }

  static String greetingForTime(String localeCode, DateTime now) {
    if (now.hour < 12) {
      return translate(localeCode, 'greetingMorning');
    }
    if (now.hour < 17) {
      return translate(localeCode, 'greetingAfternoon');
    }
    if (now.hour < 22) {
      return translate(localeCode, 'greetingEvening');
    }
    return translate(localeCode, 'greetingNight');
  }
